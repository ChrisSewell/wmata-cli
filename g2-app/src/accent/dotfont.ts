export const GLYPH_ROWS = 23;

export interface DotOpts {
  dot?: number;
  gap?: number;
  color?: string;
  raiseDegree?: number;
}

function hbounds(g: string[]): [number, number] {
  let lo = Infinity;
  let hi = -1;
  for (const row of g) for (let c = 0; c < row.length; c++) if (row[c] === "1") { if (c < lo) lo = c; if (c > hi) hi = c; }
  return hi < 0 ? [0, -1] : [lo, hi];
}

/** Draw a string of [0-9 ° : . -] as a dot matrix; returns the end x (px). */
export function drawDotString(ctx: CanvasRenderingContext2D, str: string, x: number, top: number, o: DotOpts = {}): number {
  const dot = o.dot ?? 3;
  const gap = o.gap ?? 2;
  const step = dot + gap;
  const raise = o.raiseDegree ?? 2;
  ctx.save();
  ctx.fillStyle = o.color ?? "#ffffff";
  let penX = x;
  for (const ch of str) {
    if (ch === " ") { penX += 6 * step; continue; }
    const g = GLYPHS[ch];
    if (!g) { penX += 6 * step; continue; }
    const [lo, hi] = hbounds(g);
    if (hi < 0) { penX += 6 * step; continue; }
    const yOff = ch === "°" ? raise * step : 0;
    for (let r = 0; r < g.length; r++) {
      const row = g[r]!;
      for (let c = lo; c <= hi; c++) if (row[c] === "1") ctx.fillRect(penX + (c - lo) * step, top + r * step + yOff, dot, dot);
    }
    penX += (hi - lo + 1) * step + 2 * step;
  }
  ctx.restore();
  return penX;
}

/** Pixel width of a string at the given options (for centering / layout). */
export function dotStringWidth(str: string, o: DotOpts = {}): number {
  const dot = o.dot ?? 3;
  const gap = o.gap ?? 2;
  const step = dot + gap;
  let w = 0;
  for (const ch of str) {
    if (ch === " ") { w += 6 * step; continue; }
    const g = GLYPHS[ch];
    if (!g) { w += 6 * step; continue; }
    const [lo, hi] = hbounds(g);
    w += (hi - lo + 1) * step + 2 * step;
  }
  return Math.max(0, w - 2 * step);
}

/** True if every char is a dotfont glyph (digits / ° : . -). */
export function isDotDrawable(str: string): boolean {
  for (const ch of str) if (ch !== " " && !GLYPHS[ch]) return false;
  return str.length > 0;
}
